import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";

/** 项目根目录由脚本位置决定，允许从前端 workspace 调用。 */
export const root = fileURLToPath(new URL("../", import.meta.url));

/** 以根 package.json 为唯一版本来源；检查模式只读，普通模式更新派生文件。 */
export function syncVersion(check = false, directory = root) {
  const pkg = JSON.parse(readFileSync(resolve(directory, "package.json"), "utf8"));
  if (!/^\d+\.\d+\.\d+(?:-[0-9A-Za-z]+(?:[.-][0-9A-Za-z]+)*)?$/.test(pkg.version)) {
    throw new Error(`无效的发布版本：${pkg.version}`);
  }
  if (pkg.license !== "MIT") throw new Error("Vela 自有代码必须保持已确认的 MIT 许可");
  const frontendPath = resolve(directory, "frontend/package.json");
  const frontend = JSON.parse(readFileSync(frontendPath, "utf8"));
  frontend.version = pkg.version;
  frontend.license = pkg.license;
  const lockPath = resolve(directory, "package-lock.json");
  const lock = JSON.parse(readFileSync(lockPath, "utf8"));
  lock.version = pkg.version;
  for (const name of ["", "frontend"]) {
    lock.packages[name].version = pkg.version;
    lock.packages[name].license = pkg.license;
  }
  const go = `// Code generated by scripts/release-version.mjs; DO NOT EDIT.

// Package buildinfo 提供从根 package.json 派生的应用版本。
package buildinfo

// Version 是运行时、前端与安装包共用的发布版本。
const Version = "${pkg.version}"
`;
  for (const [path, value] of [[frontendPath, JSON.stringify(frontend, null, 2) + "\n"], [lockPath, JSON.stringify(lock, null, 2) + "\n"], [resolve(directory, "internal/buildinfo/buildinfo.go"), go]]) {
    if (readFileSync(path, "utf8") === value) continue;
    if (check) throw new Error(`版本文件不同步：${path}；请运行 npm run version:sync`);
    writeFileSync(path, value);
  }
  return pkg.version;
}

/** 保留 Vite 原有命令行参数，支持独立端口和隔离验收。 */
export function frontendArguments(mode, args = []) {
  return [...(mode === "build" ? ["build"] : []), ...args];
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args[0] === "--frontend" && ["dev", "build"].includes(args[1])) {
    const version = syncVersion(true);
    const result = spawnSync(process.execPath, [resolve(root, "node_modules/vite/bin/vite.js"), ...frontendArguments(args[1], args.slice(2))], {
      cwd: resolve(root, "frontend"), stdio: "inherit", env: { ...process.env, VITE_VELA_VERSION: version },
    });
    if (result.error) throw result.error;
    process.exit(result.status ?? 1);
  }
  if (args.length && !(args.length === 1 && args[0] === "--check")) throw new Error("用法：release-version.mjs [--check | --frontend dev|build]");
  console.log(`Vela ${syncVersion(args[0] === "--check")}`);
}
