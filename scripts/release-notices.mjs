import { existsSync, readFileSync, readdirSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { root } from "./release-version.mjs";

/** 收集适用的许可、版权、专利及继承声明文件，保留上游全文。 */
function licenseFiles(directory) {
  return readdirSync(directory, { withFileTypes: true }).filter((entry) => entry.isFile() && /^(licen[cs]e|copying|notice|patents)([._-]|$)/i.test(entry.name) && entry.name !== "LICENSE-LOGO").map((entry) => join(directory, entry.name)).sort();
}

/** 按 npm 的父级 node_modules 搜索规则定位包，兼容禁止导出 package.json 的包。 */
function packageDirectory(name, from) {
  for (let directory = from; ; directory = dirname(directory)) {
    const candidate = join(directory, "node_modules", name);
    if (existsSync(join(candidate, "package.json"))) return realpathSync(candidate);
    if (dirname(directory) === directory) throw new Error(`找不到前端依赖：${name}`);
  }
}

/** 为 macOS 两种架构生成可复核的全文清单，不运行桌面入口或访问用户数据。 */
export function notices() {
  const entries = new Map();
  /** 同一来源只收录一次，避免相同许可证通过多个包重复展开。 */
  function add(label, file) {
    const text = readFileSync(file, "utf8").trim();
    if (!text) throw new Error(`许可文件为空：${file}`);
    entries.set(label, text);
  }
  const env = { ...process.env, CGO_ENABLED: "0", GOOS: "darwin" };
  const goroot = execFileSync("go", ["env", "GOROOT"], { cwd: root, encoding: "utf8" }).trim();
  const goversion = execFileSync("go", ["env", "GOVERSION"], { cwd: root, encoding: "utf8" }).trim();
  for (const file of licenseFiles(goroot)) add(`Go ${goversion} / ${relative(goroot, file)}`, file);
  for (const arch of ["arm64", "amd64"]) {
    const lines = execFileSync("go", ["list", "-deps", "-tags=mygo_noinspector", "-f", "{{.Dir}}\t{{with .Module}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}", "./cmd/vela"], { cwd: root, env: { ...env, GOARCH: arch }, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 }).trim().split("\n");
    for (const line of lines) {
      const [directory, module, version, moduleRoot] = line.split("\t");
      if (module === "github.com/CodeZen-Lizhi/vela") continue;
      const base = moduleRoot || goroot;
      const label = module ? `${module} ${version}` : `Go ${goversion}`;
      // 子包可能沿用祖先目录的许可；不扫描未导入的测试和示例目录。
      for (let current = directory; ; current = dirname(current)) {
        for (const file of licenseFiles(current)) add(`${label} / ${relative(base, file)}`, file);
        if (current === base) break;
        if (dirname(current) === current) throw new Error(`Go 依赖目录不在模块内：${directory}`);
      }
      if (module && licenseFiles(base).length === 0) throw new Error(`Go 模块缺少许可文件：${module}`);
    }
  }
  const frontend = JSON.parse(readFileSync(join(root, "frontend/package.json"), "utf8"));
  // 这些 devDependencies 在页面中作为运行时组件或生成样式使用；递归保留其依赖全文。
  const runtime = ["bits-ui", "paneforge", "svelte", "svelte-sonner", "tailwind-variants", "tailwindcss", "@internationalized/date"];
  const visited = new Set();
  /** 依照实际安装树遍历前端组件及其依赖，包含嵌套的不同版本。 */
  function addPackage(name, from) {
    const directory = packageDirectory(name, from);
    if (visited.has(directory)) return;
    visited.add(directory);
    const pkg = JSON.parse(readFileSync(join(directory, "package.json"), "utf8"));
    const files = licenseFiles(directory);
    if (!files.length) throw new Error(`前端包缺少许可全文：${pkg.name}@${pkg.version}`);
    for (const file of files) add(`npm ${pkg.name}@${pkg.version} (${pkg.license || "see license"}) / ${relative(directory, file)}`, file);
    // Svelte 浏览器入口只引入 esm-env/clsx；其 AST 编译工具不会进入发行包。
    const dependencies = pkg.name === "svelte" ? ["esm-env", "clsx"] : Object.keys(pkg.dependencies || {}).sort();
    for (const dependency of dependencies) addPackage(dependency, directory);
  }
  for (const name of [...Object.keys(frontend.dependencies), ...runtime].sort()) addPackage(name, join(root, "frontend"));
  add("Lobe Icons @lobehub/icons-static-svg 1.102.0 / MIT (frontend/src/lib/assets/providers)", join(root, "frontend/src/lib/assets/providers/LICENSE"));
  add("lm-detector a7e9d3056e019827904dd50722c20b4a0c896738 / MIT (internal/verification/fingerprint; code and bundled bank/detector data)", join(root, "internal/verification/fingerprint/LICENSE"));
  add("shadcn-svelte / MIT (frontend/src/lib/components/ui; upstream LICENSE at 28f5a3bef5ea7934044a7fb60a3e6f201b3b090a)", join(root, "THIRD_PARTY_NOTICES.shadcn-svelte.txt"));
  const sections = [...entries].sort(([a], [b]) => a.localeCompare(b, "en"));
  return `Vela — Third-Party Notices

Generated by scripts/release-notices.mjs from the installed dependencies.
Vela-owned code: MIT, Copyright (c) 2026 CodeZen; see LICENSE.
Third-party code, fonts, icons and data retain their respective terms below.
Scope: macOS arm64/amd64 Go dependency packages and Go standard library;
frontend runtime/component/style dependencies and their dependency closure.
Inherited notices are reproduced in full even when only part of a dependency
package reaches the app. Svelte compiler-only dependencies are excluded.
Operating-system frameworks are supplied by macOS, not redistributed here.
Source links identify provenance; the required license texts follow in full.

Contents (${sections.length} license/notice files):
${sections.map(([label]) => `- ${label}`).join("\n")}
\n${sections.map(([label, text]) => `${"=".repeat(78)}\n${label}\n${"=".repeat(78)}\n\n${text}\n`).join("\n")}`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length && !(args.length === 1 && args[0] === "--check")) throw new Error("用法：release-notices.mjs [--check]");
  const expected = notices();
  const file = join(root, "THIRD_PARTY_NOTICES.txt");
  if (args[0] === "--check") {
    if (!existsSync(file) || readFileSync(file, "utf8") !== expected) throw new Error("第三方许可清单已过期；请运行 npm run licenses:generate");
  } else writeFileSync(file, expected);
  console.log(`第三方许可全文：${Buffer.byteLength(expected)} bytes`);
}
